def verify_kokugo(meta, questions):
    """資料の数値を図法の定義から再計算して照合し、根拠が本文に実在するか見る。"""
    errs = []
    for lat in LATS:
        want = f"<td>{lat}度</td><td>{stretch(lat):.2f}</td><td>{stretch(lat) ** 2:.1f}</td>"
        if want not in SHIRYO:
            errs.append(f"資料の {lat} 度の行が計算と合わない")
    # 解説の【本文の根拠】で「」に入れた引用が、本文か資料に実在するか
    import re
    body = re.sub(r"<[^>]+>", "", HONBUN + SHIRYO)
    body = re.sub(r"\s+", "", body)
    for q in questions:
        exp = q["explanation"]
        konkyo = exp.split("【本文の根拠】")[1].split("【正解の理由】")[0]
        for quote in re.findall(r"「([^「」]{6,})」", konkyo):
            if re.sub(r"\s+", "", quote) not in body:
                errs.append(f"第{q['number']}問: 解説の引用が本文に無い "
                            f"({quote[:20]!r})")
    return errs


