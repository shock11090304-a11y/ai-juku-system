def verify_rika(meta, questions):
    """表の数値を等加速度運動の式から再計算して照合する。"""
    errs = []
    for k in range(N_TAPE):
        want = f"<td>{k + 1}</td><td>{LENGTHS_M[k] * 100:.1f}</td>"
        if want not in JIKKEN:
            errs.append(f"表の {k + 1} 本目が計算と合わない")
    if abs(DT - 0.1) > 1e-9:
        errs.append(f"テープ 1 本の時間が 0.1 秒でない ({DT})")
    for k in range(1, N_TAPE):
        a = (SPEEDS[k] - SPEEDS[k - 1]) / (MIDS[k] - MIDS[k - 1])
        if abs(a - ACC) > 1e-9:
            errs.append(f"表から出る加速度が {ACC} でない ({k + 1} 本目で {a})")
    total = sum(LENGTHS_M)
    if abs(total - 0.5 * ACC * (N_TAPE * DT) ** 2) > 1e-9:
        errs.append("テープの長さの合計が ½at² と合わない")
    return errs


