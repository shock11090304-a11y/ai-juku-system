# ---------------------------------------------------------------- 検算用の道具
def _med(a):
    """並べ替え済み list の中央値（偶数個は真ん中2つの平均・Fraction で厳密に）。"""
    n = len(a)
    return a[n // 2] if n % 2 else Fraction(a[n // 2 - 1] + a[n // 2], 2)


def _quartiles(d):
    """生データから Q1, Q2, Q3 を独立に計算する（奇数個は中央値を両グループから除く）。"""
    s = sorted(d)
    n = len(s)
    return _med(s[:n // 2]), _med(s), _med(s[(n + 1) // 2:])


def _pvar(d):
    """母分散を定義（偏差の2乗の平均）どおりに計算する。"""
    m = Fraction(sum(d), len(d))
    return sum((Fraction(v) - m) ** 2 for v in d) / len(d)


def _box_sim(trials=30000):
    """五数要約が (2,4,6,8,10) の 30 人分のデータを乱数で多数作り、
    6 点以上の人数がいくつまで小さくなれるかを実験で確かめる。
    戻り値 = (該当データの個数, 6 点以上の人数の最小値)。"""
    rnd = random.Random(20260807)   # グローバルな乱数種は触らない（他のゲートに影響させない）
    got = []
    for _ in range(trials):
        s = sorted(rnd.randint(2, 10) for _ in range(30))
        if (s[0] == 2 and s[29] == 10 and s[7] == 4 and s[22] == 8
                and s[14] + s[15] == 12):
            got.append(sum(1 for v in s if v >= 6))
    return len(got), (min(got) if got else -1)


# ---------------------------------------------------------------- 図（箱ひげ図）
def _boxplot(lo, q1, q2, q3, hi, xmax=10):
    """五数要約から箱ひげ図を描く（点は実際に計算して置く）。"""
    cv = Canvas(xr=(-0.6, xmax + 0.6), yr=(-1.6, 1.5), size=(320, 125), pad=14)
    # ひげ（先に引いて、箱で隠れるようにする）
    cv.seg(lo, 0.6, q1, 0.6, w=1.4)
    cv.seg(q3, 0.6, hi, 0.6, w=1.4)
    # ひげの端の縦棒
    cv.seg(lo, 0.28, lo, 0.92, w=1.4)
    cv.seg(hi, 0.28, hi, 0.92, w=1.4)
    # 箱
    cv.poly([(q1, 0.15), (q3, 0.15), (q3, 1.05), (q1, 1.05)], fill=FILL, stroke=NAVY, w=1.6)
    # 中央値の縦線
    cv.seg(q2, 0.15, q2, 1.05, w=2.0)
    # 目盛りの数直線
    cv.seg(0, -0.75, xmax, -0.75, w=1.1)
    for v in range(0, xmax + 1):
        cv.seg(v, -0.75, v, -0.95, w=1.0)
    for v in range(0, xmax + 1, 2):
        cv.label(v, -0.95, str(v), dx=-3.2 * len(str(v)), dy=13, size=10)
    return cv.svg()


