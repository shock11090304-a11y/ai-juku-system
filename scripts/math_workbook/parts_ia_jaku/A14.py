# ------------------------------------------- chk 用の「独立に再計算する」道具
def _mean(v):
    return sp.Rational(sum(v), len(v))


def _cov_dev(xs, ys):
    """定義どおり（偏差の積の平均）で共分散を出す。"""
    n = len(xs)
    mx, my = _mean(xs), _mean(ys)
    return sum((sp.Integer(a) - mx) * (sp.Integer(b) - my) for a, b in zip(xs, ys)) / n


def _stats2(xs, ys):
    """『積の平均 − 平均の積』ルートで (分散x, 分散y, 共分散) を返す。
    解説が使う偏差ルートとは別経路なので、両方が一致すれば計算が独立に裏付けられる。"""
    n = len(xs)
    mx, my = _mean(xs), _mean(ys)
    vx = sp.Rational(sum(a * a for a in xs), n) - mx ** 2
    vy = sp.Rational(sum(b * b for b in ys), n) - my ** 2
    cxy = sp.Rational(sum(a * b for a, b in zip(xs, ys)), n) - mx * my
    return vx, vy, cxy


def _corr(xs, ys):
    """生データから相関係数を float で返す。"""
    vx, vy, cxy = _stats2(xs, ys)
    return float(cxy / sp.sqrt(vx * vy))


