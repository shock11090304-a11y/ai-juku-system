from svgfig import Canvas

x, y, k = symbols('x y k', real=True)


def _fig_parabola():
    """A08-7 用: 放物線 y=x^2+3x+2 だけを描く(直線は答えを漏らすので描かない)。
    点は実際に計算してつなぐ — 手打ち SVG は必ず上下が逆になる。

    ★y レンジは頂点の深さ 0.25 に対して詰めること。Canvas の倍率は
      min(sx, sy) の等倍なので、y レンジを広く取ると x 軸より下の凹みが
      線幅の数倍しか無くなり、紙の上では「x 軸に接している」ようにしか見えない
      (この問題は接する条件を問うので、接点 (-1,0) と混同する経路ができる)。
      枠外は A06 の _para と同じく描かずに切る。
    """
    xr, yr = (-3.6, 0.6), (-1.0, 2.8)
    c = Canvas(xr=xr, yr=yr, size=(200, 170))
    c.axes()
    f = lambda t: t * t + 3 * t + 2
    n = 200
    prev = None
    for i in range(n + 1):
        xv = xr[0] + (xr[1] - xr[0]) * i / n
        yv = f(xv)
        cur = (xv, yv) if c.ymin <= yv <= c.ymax else None
        if prev is not None and cur is not None:
            c.seg(prev[0], prev[1], cur[0], cur[1], w=1.6)
        prev = cur
    # ★w_mm 未指定だと CSS の .fig svg{max-height:44mm} が寸法を決め、実効スケールが
    #   44/170 まで落ちて軸ラベル(font-size 10)が 6.65pt しかなかった(本文 9.7pt)。
    #   作図はそのまま、紙の幅だけ固定して 9.38pt にする。
    return c.svg(w_mm=73.0)


