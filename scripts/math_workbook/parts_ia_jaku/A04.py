def _subsets(seq):
    """seq の部分集合を「全列挙」する。2^n の公式を使わないので、
    公式で出した答えの独立な検算になる。"""
    seq = list(seq)
    out = []
    for r in range(len(seq) + 1):
        for c in itertools.combinations(seq, r):
            out.append(frozenset(c))
    return out


def _solve_regions3(nA, nB, nC, nAB, nBC, nAC, nABC, total):
    """ベン図の 8 つの部屋の人数を連立1次方程式として sympy に解かせる。
    包除原理の式を一切使わないので、包除原理で出した答えの独立な検算になる。
    戻り値 (少なくとも1つに属する人数, どれにも属さない人数)。矛盾すれば None。"""
    keys = list(itertools.product((0, 1), repeat=3))
    v = {k: sp.Symbol("r%d%d%d" % k) for k in keys}
    eqs = [
        sp.Eq(sum(v[k] for k in keys if k[0]), nA),
        sp.Eq(sum(v[k] for k in keys if k[1]), nB),
        sp.Eq(sum(v[k] for k in keys if k[2]), nC),
        sp.Eq(sum(v[k] for k in keys if k[0] and k[1]), nAB),
        sp.Eq(sum(v[k] for k in keys if k[1] and k[2]), nBC),
        sp.Eq(sum(v[k] for k in keys if k[0] and k[2]), nAC),
        sp.Eq(sum(v[k] for k in keys if all(k)), nABC),
        sp.Eq(sum(v[k] for k in keys), total),
    ]
    sols = sp.solve(eqs, [v[k] for k in keys], dict=True)
    if not sols:
        return None
    rooms = {k: sp.Integer(sols[0][v[k]]) for k in keys}
    if any(r < 0 for r in rooms.values()):
        return None
    return (sum(r for k, r in rooms.items() if any(k)), rooms[(0, 0, 0)])


