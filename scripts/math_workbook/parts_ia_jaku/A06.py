def _para(cv, f, x0, x1, n=90, stroke=NAVY, w=1.8):
    """関数 f のグラフを実際に点を計算して折れ線で描く（枠外は自動で切る）。"""
    prev = None
    for i in range(n + 1):
        xv = x0 + (x1 - x0) * i / n
        yv = f(xv)
        cur = (xv, yv) if cv.ymin <= yv <= cv.ymax else None
        if prev is not None and cur is not None:
            cv.seg(prev[0], prev[1], cur[0], cur[1], stroke=stroke, w=w)
        prev = cur


