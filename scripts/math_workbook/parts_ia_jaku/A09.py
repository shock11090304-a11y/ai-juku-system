def _parabola(c, f, x0, x1, step=0.05, stroke=NAVY, w=1.7):
    """y=f(x) を折れ線で描く。★点は必ず計算する（手打ち座標は上下が逆になる）。"""
    n = int(round((x1 - x0) / step))
    pts = [(x0 + step * i, f(x0 + step * i)) for i in range(n + 1)]
    for (ax, ay), (bx, by) in zip(pts, pts[1:]):
        c.seg(ax, ay, bx, by, stroke=stroke, w=w)


def _fig_convex_down():
    """P1 用。y=2x^2-5x-3 の概形（下に凸・x 軸を2点で切る）。
    ★交点の値を書くと答えそのものになるので、目盛りも数値も置かない。"""
    f = lambda v: 2 * v ** 2 - 5 * v - 3
    c = Canvas((-1.6, 4.2), (-7.0, 3.0), SZ)
    c.axes(olabel=False)
    _parabola(c, f, -0.85, 3.35)          # f(x)=3 になる x の内側だけ描く
    for v in (R(-1, 2), 3):
        c.dot(float(v), 0)
    # ★原点ラベル O は既定位置（原点の左下・dx=-11, dy=+12）だと放物線に貫かれる。
    #   左の枝は x 軸を切ったあと原点のすぐ左下を急降下していく（実測 余白 0.00px）。
    #   → 原点の右下へ逃がす。右下は頂点へ向かって曲線が大きく下がっており空いている。
    c.label(0, 0, "O", dx=4, dy=12, size=10)
    return c.svg(w_mm=W_MM)


def _fig_convex_up():
    """P2 用。y=-x^2+6x-5 の概形（上に凸・x 軸を2点で切る）。数値は置かない。"""
    f = lambda v: -v ** 2 + 6 * v - 5
    c = Canvas((-1.0, 6.4), (-3.2, 5.0), SZ)
    c.axes()
    _parabola(c, f, 0.36, 5.64)           # f(x)=-3 になる x の内側だけ描く
    for v in (1, 5):
        c.dot(v, 0)
    return c.svg(w_mm=W_MM)


def _p5_gt1(mv):
    """m を具体値にして 2次方程式を実際に解き、「異なる2実数解がともに 1 より大」かを見る。
    ★判別式・軸・端点の3条件を一切使わない独立ルート（解の配置の理屈ごと検算する）。"""
    rs = sp.solve(sp.Eq(x ** 2 - 2 * (mv - 2) * x + mv + 4, 0), x)
    rs = [r for r in rs if r.is_real]
    return bool(len(rs) == 2 and all(r > 1 for r in rs))


def _p6_flags(mv):
    """m を具体値にして 2次方程式を実際に解き、実数解の符号を見る。
    ★判別式・軸・端点の3条件を一切使わない独立ルート（解の配置の理屈ごと検算する）。"""
    rs = sp.solve(sp.Eq(x ** 2 - 2 * (mv - 1) * x + mv + 5, 0), x)
    rs = sorted([r for r in rs if r.is_real], key=lambda v: sp.N(v))
    both_pos = bool(len(rs) == 2 and all(r > 0 for r in rs))
    opposite = bool(len(rs) == 2 and rs[0] * rs[1] < 0)
    return (both_pos, opposite)


