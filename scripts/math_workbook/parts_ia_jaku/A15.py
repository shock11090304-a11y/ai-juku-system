def _chk_cafe():
    """飲み物5・ケーキ4・サンドイッチ3 の組を実際に列挙して数える。"""
    drinks, cakes, sands = range(5), range(4), range(3)
    both = [(d, c) for d in drinks for c in cakes]
    either = ([(d, ("cake", c)) for d in drinks for c in cakes]
              + [(d, ("sand", s)) for d in drinks for s in sands])
    return len(both) == 20 and len(either) == 35


def _chk_card3():
    """0〜5 の数字で3桁を全通りつくり、先頭が 0 でないものを数える。(1)重複なし (2)重複あり。"""
    once = [p for p in permutations(range(6), 3) if p[0] != 0]      # 同じ数字は1回まで
    many = [p for p in product(range(6), repeat=3) if p[0] != 0]    # 同じ数字を何回でも
    # 実際に整数に直しても個数が減らない(別の並びが同じ整数にならない)ことも確認する
    i1 = {a * 100 + b * 10 + c for a, b, c in once}
    i2 = {a * 100 + b * 10 + c for a, b, c in many}
    return (len(once) == 100 and len(i1) == 100
            and len(many) == 180 and len(i2) == 180
            and min(i1) >= 100 and min(i2) >= 100 and i1 < i2)


def _chk_row7():
    """男子3(=0,1,2)・女子4 の 7! 通りを全列挙し、(1)3人が続く (2)どの2人も隣り合わない を数える。"""
    tight = loose = 0
    for p in permutations(range(7)):
        pos = sorted(i for i, v in enumerate(p) if v < 3)
        if pos[2] - pos[0] == 2:
            tight += 1
        if pos[1] - pos[0] >= 2 and pos[2] - pos[1] >= 2:
            loose += 1
    return tight == 720 and loose == 1440


def _chk_round6():
    """6席の円卓に6人を座らせる全通りを列挙し、回転(6通り)で割ってから大人が隣り合う数を出す。"""
    n = 0
    for p in permutations(range(6)):        # p[i] = 席 i に座る人。0,1 が大人
        i, j = p.index(0), p.index(1)
        if (i - j) % 6 in (1, 5):
            n += 1
    return n // 6 == 48


def _chk_groups9():
    """9人を3人ずつ3組に分ける方法を実際に列挙する。名前つきは通り数、名前なしは集合として重複を潰す。"""
    people = list(range(9))
    labeled, unlabeled = 0, set()
    for a in combinations(people, 3):
        rest = [x for x in people if x not in a]
        for b in combinations(rest, 3):
            c = tuple(x for x in rest if x not in b)
            labeled += 1
            unlabeled.add(frozenset((frozenset(a), frozenset(b), frozenset(c))))
    return labeled == 1680 and len(unlabeled) == 280


