def _pct(part, total):
    """部門の産出額（億円）が総額にしめる割合（％・小数第1位）。"""
    return round(part / total * 100, 1)


def _pref_pcts(row):
    """(米, 野菜, 果実, 畜産, その他) の構成比。その他＝総額－4部門。"""
    _, _, tot, rice, veg, fruit, live = row
    other = tot - (rice + veg + fruit + live)
    return [_pct(x, tot) for x in (rice, veg, fruit, live, other)]


def _hm(d):
    """datetime -> '8月10日 午前3時'（分が0でないときは '午前3時30分'）。"""
    ampm = "午前" if d.hour < 12 else "午後"
    h = d.hour % 12
    s = f"{d.month}月{d.day}日 {ampm}{h}時"
    return s + (f"{d.minute}分" if d.minute else "")


