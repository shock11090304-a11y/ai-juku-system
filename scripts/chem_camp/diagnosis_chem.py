def index():
    """{"C03-4": {"unit":3,"no":4,"unit_name":..,"skill":..,"level":..,"stem":..}} を返す。"""
    out, uno = {}, 0
    for p in C.PARTS:
        for u in p["units"]:
            uno += 1
            # build_chem と同じ並べ替え(group 初出順)で採番する
            order, buckets = [], {}
            for q in u["problems"]:
                g = q.get("group", "")
                if g not in buckets:
                    buckets[g] = []
                    order.append(g)
                buckets[g].append(q)
            probs = [q for g in order for q in buckets[g]]
            for j, q in enumerate(probs, 1):
                out[f"C{uno:02d}-{j}"] = {
                    "unit": uno, "no": j, "area": p["area"], "unit_name": u["name"],
                    "skill": q["skill"], "level": q["level"], "stem": q["stem"],
                    "answer": q.get("answer", ""),
                }
    return out


def units_info():
    out, uno = [], 0
    for p in C.PARTS:
        for u in p["units"]:
            uno += 1
            out.append({"idx": uno, "name": u["name"].split("【")[0],
                        "area": p["area"], "count": len(u["problems"])})
    return out
