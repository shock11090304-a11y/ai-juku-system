"""正解の位置（①〜⑤のどこに置くか）の一覧。ここが正典で、各回の原稿には書かない。

   手で振ると必ず偏る。ここは次を満たすように機械で選んだ並びである。
     ・全42小問で ①〜⑤ が 8〜9 回ずつ
     ・1つの回（7小問）の中で同じ番号は2回まで
     ・★同じ設問番号を回ごとに縦に並べたとき（問2 の列など）も、同じ番号は2回まで
       （分布と並び順だけを均しても、「問2はいつも⑤」と覚えられる穴が残る。
         実際に最初の表は 問2 が ⑤⑤⑤ と3回続いていた）
     ・★回どうしで並びがそっくりにならない（問1(ア)(イ)(ウ)の3つ組も含めて）
     ・隣どうしが同じ番号にならない。3小問続けて等差にもならない
     ・「+n ずつずれる」といった遷移の癖がない（最大でも約27%）
   ★本文を読まずに位置だけで当てられないようにするための仕掛けなので、
     設問を差し替えても、この表の値のほうは動かさないこと。
   ★正しく配れているかは check.py（分布）と audit.py（遷移の癖）が毎回見る。
"""

POS = {
    1: [5, 2, 3, 5, 4, 2, 1],
    2: [2, 1, 5, 4, 5, 2, 1],
    3: [4, 5, 3, 4, 1, 5, 3],
    4: [2, 5, 2, 5, 3, 4, 3],
    5: [1, 4, 1, 3, 4, 3, 5],
    6: [1, 2, 4, 1, 3, 4, 2],
}

def of(set_id, k):
    """第 set_id 回の、k 番目（0 始まり）の小問に置く正解の番号"""
    if set_id not in POS: raise SystemExit(f"第{set_id}回の正解位置が positions.py に無い")
    row = POS[set_id]
    if not 0 <= k < len(row): raise SystemExit(f"第{set_id}回: 小問が {len(row)} 個を超えている")
    return row[k]
